var currentLang = "it";

function readLang() {
  var value = new URLSearchParams(window.location.search).get("lang");
  return value === "en" || value === "it" ? value : "it";
}

function setLang(lang, updateUrl) {
  var copy = COPY[lang];
  currentLang = lang;
  document.documentElement.lang = lang;
  document.title = lang === "it" ? "Micometeo: scegli un bosco per i porcini" : "Micometeo: choose a forest for porcini";
  document.querySelectorAll("[data-i18n]").forEach(function (node) {
    node.textContent = copy[node.getAttribute("data-i18n")];
  });
  document.querySelectorAll("[data-i18n-html]").forEach(function (node) {
    node.innerHTML = copy[node.getAttribute("data-i18n-html")];
  });
  document.querySelectorAll("[data-lang-label]").forEach(function (node) {
    var active = node.getAttribute("data-lang-label") === lang;
    node.classList.toggle("text-primary", active);
    node.classList.toggle("font-bold", active);
  });
  document.querySelectorAll("[data-app-link]").forEach(function (link) {
    link.setAttribute("href", "app.html?lang=" + lang);
  });
  document.querySelectorAll("[data-lang-link]").forEach(function (link) {
    link.setAttribute("href", "landing.html?lang=" + lang);
  });
  if (updateUrl) {
    history.replaceState(null, "", "?lang=" + lang + window.location.hash);
  }
}

document.getElementById("lang-toggle").addEventListener("click", function () {
  setLang(currentLang === "it" ? "en" : "it", true);
});

setLang(readLang(), false);
